/**
 * Regenerates config/user-guide.ts from the Strapi `user-guide-sections` collection.
 *
 *   pnpm nx run platform:user-guide:sync       # production CMS (STRAPI_URL_PRO / STRAPI_TOKEN_PRO)
 *   pnpm nx run platform:user-guide:sync:dev   # dev CMS (STRAPI_URL / STRAPI_TOKEN), debugging only
 *
 * Reads the keys from apps/platform/.env. Commit the result: the slugs are literal types, so the
 * file has to exist at typecheck time, not be fetched at runtime.
 */
import { writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

// Production is the source of truth: the published guide is what users can open.
const suffix = process.argv.includes('--dev') ? '' : '_PRO'
const STRAPI_URL = process.env[`STRAPI_URL${suffix}`]
const STRAPI_TOKEN = process.env[`STRAPI_TOKEN${suffix}`] ?? ''
if (!STRAPI_URL) {
  throw new Error(`STRAPI_URL${suffix} is not set in apps/platform/.env`)
}

const outFile = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../user-guide.ts')

// Same sort as features/cms/user-guide.serverfn.ts, so the object keys follow the menu order.
const query = new URLSearchParams({
  'fields[0]': 'slug',
  'populate[subsections][fields][0]': 'slug',
  sort: 'createdAt:asc',
  locale: 'en',
  'pagination[pageSize]': '100',
})

const response = await fetch(new URL(`/api/user-guide-sections?${query}`, STRAPI_URL), {
  headers: STRAPI_TOKEN ? { Authorization: `Bearer ${STRAPI_TOKEN}` } : {},
})
if (!response.ok) {
  throw new Error(`Strapi responded ${response.status}: ${await response.text()}`)
}
const { data, meta } = await response.json()
if (meta.pagination.total > data.length) {
  throw new Error(`Got ${data.length} of ${meta.pagination.total} sections, raise pageSize`)
}

const sections = Object.fromEntries(
  data.map(({ slug, subsections = [] }) => [slug, subsections.map((s) => s.slug)])
)

await writeFile(
  outFile,
  `/**
 * User guide section slugs (Strapi \`user-guide-sections\`) and the subsection slugs each one can
 * link to.
 * GENERATED by config/scripts/generate-user-guide.mjs — run \`pnpm nx run platform:user-guide:sync\`.
 */
export const USER_GUIDE_SECTIONS = ${JSON.stringify(sections, null, 2)} as const
`
)
console.log(`Wrote ${data.length} sections to ${path.relative(process.cwd(), outFile)}`)
